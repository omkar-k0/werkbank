/*
 * Evaluates the seed models on data never used for training or calibration.
 *   - data/test.json        800 synthetic, unseen templates + unseen synonyms
 *   - data/handwritten.json 60 hand-written messy requests (EN + DE)
 * Also simulates the feedback loop: a shop whose staff phrase things
 * differently corrects k orders, then we measure on later orders.
 * Writes reports/eval.md and reports/eval.json.
 *
 *   npx tsx scripts/eval.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { buildShopModels, classify, type Correction } from "../src/lib/classifier";
import { CAPABILITIES, type Capability, type LabeledExample } from "../src/lib/classifier/types";

const test: LabeledExample[] = JSON.parse(readFileSync("data/test.json", "utf8"));
const hand: LabeledExample[] = JSON.parse(readFileSync("data/handwritten.json", "utf8"));
const pct = (x: number) => `${(100 * x).toFixed(1)}%`;

function evaluate(rows: LabeledExample[], corrections: Correction[] = []) {
  const models = buildShopModels(corrections);
  let top1 = 0, job = 0;
  const gates = { auto: { n: 0, ok: 0 }, check: { n: 0, ok: 0 }, review: { n: 0, ok: 0 } };
  const confusion: Record<string, Record<string, number>> = {};
  const misses: { text: string; truth: string; got: string; gate: string; conf: number }[] = [];
  for (const r of rows) {
    const c = classify(r.text, models);
    const guess = (Object.entries(c.routing.probabilities) as [Capability, number][]).sort((a, b) => b[1] - a[1])[0][0];
    const ok = guess === r.capability;
    top1 += +ok;
    job += +(c.labels.jobType === r.jobType);
    const g = gates[c.routing.gate];
    g.n++;
    g.ok += +ok;
    confusion[r.capability] ??= {};
    confusion[r.capability][guess] = (confusion[r.capability][guess] ?? 0) + 1;
    if (!ok && c.routing.gate !== "review") misses.push({ text: r.text, truth: r.capability, got: guess, gate: c.routing.gate, conf: +c.routing.confidence.toFixed(2) });
  }
  const n = rows.length;
  const routed = gates.auto.n + gates.check.n;
  return {
    n,
    top1: top1 / n,
    jobType: job / n,
    autoRate: gates.auto.n / n,
    autoAcc: gates.auto.n ? gates.auto.ok / gates.auto.n : null,
    checkRate: gates.check.n / n,
    checkAcc: gates.check.n ? gates.check.ok / gates.check.n : null,
    reviewRate: gates.review.n / n,
    // what a shop actually experiences: of orders routed without review, how many were right
    routedAcc: routed ? (gates.auto.ok + gates.check.ok) / routed : null,
    confusion,
    misses,
  };
}

const rTest = evaluate(test);
const rHand = evaluate(hand);

// feedback loop: first k test orders become corrections, measure on the last 400
const stream = test.slice(0, 400);
const holdout = test.slice(400);
const curve = [0, 25, 50, 100, 200, 400].map((k) => {
  const corr = stream.slice(0, k).map((r) => ({ text: r.text, capability: r.capability, jobType: r.jobType }));
  const r = evaluate(holdout, corr);
  return { corrections: k, top1: r.top1, autoRate: r.autoRate, autoAcc: r.autoAcc, reviewRate: r.reviewRate };
});

// threshold sweep on the synthetic test set: shown for transparency, not used to pick defaults
const sweepModels = buildShopModels([]);
const scored = test.map((r) => {
  const c = classify(r.text, sweepModels);
  const top = (Object.entries(c.routing.probabilities) as [Capability, number][]).sort((a, b) => b[1] - a[1]);
  return { conf: top[0][1], margin: top[0][1] - top[1][1], ok: top[0][0] === r.capability };
});
const sweep = [0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.95].map((a) => {
  const m = Math.min(0.5, a - 0.3);
  const band = scored.filter((s) => s.conf >= a && s.margin >= m);
  return { auto: a, margin: +m.toFixed(2), share: band.length / scored.length, acc: band.length ? band.filter((s) => s.ok).length / band.length : null };
});

const seed = JSON.parse(readFileSync("src/lib/classifier/seed-model.json", "utf8"));

function table(name: string, r: ReturnType<typeof evaluate>) {
  return `### ${name} (n = ${r.n})

| Metric | Value |
|---|---|
| Top-1 workshop accuracy (ignoring the gate) | ${pct(r.top1)} |
| Auto-routed share | ${pct(r.autoRate)} |
| Accuracy of auto-routed orders | ${r.autoAcc === null ? "n/a" : pct(r.autoAcc)} |
| Routed-but-flagged share ("check") | ${pct(r.checkRate)} |
| Accuracy of flagged orders | ${r.checkAcc === null ? "n/a" : pct(r.checkAcc)} |
| Sent to review queue | ${pct(r.reviewRate)} |
| Accuracy of everything routed without review | ${r.routedAcc === null ? "n/a" : pct(r.routedAcc)} |
| Job type accuracy | ${pct(r.jobType)} |

Confusion (rows = truth, columns = top guess):

| | ${CAPABILITIES.join(" | ")} |
|---|${CAPABILITIES.map(() => "---").join("|")}|
${CAPABILITIES.map((t) => `| **${t}** | ${CAPABILITIES.map((g) => r.confusion[t]?.[g] ?? 0).join(" | ")} |`).join("\n")}
`;
}

const md = `# Classifier evaluation

Generated by \`scripts/eval.ts\` on ${new Date().toISOString().slice(0, 10)}.
Seed model trained on ${seed.meta.trainedOn} synthetic requests. Calibrated temperature ${seed.meta.temperatureCapability},
gate thresholds: auto >= ${seed.thresholds.auto} (margin >= ${seed.thresholds.autoMargin}), check >= ${seed.thresholds.check}.

**Read this first:** all training data is synthetic. The test sets below were not used for training or for
choosing thresholds, but synthetic test data is still easier than real shop tickets. Treat these as a
lower bound on how wrong things can get, not a promise.

${table("Synthetic test set: unseen templates and unseen synonyms", rTest)}
${table("Hand-written requests (messy, mixed English/German, some deliberately vague)", rHand)}

### Wrongly routed hand-written requests (not caught by the review gate)

${rHand.misses.length ? rHand.misses.map((m) => `- "${m.text}": truth **${m.truth}**, routed to **${m.got}** (${m.gate}, ${m.conf})`).join("\n") : "None."}

### Gate strictness trade-off (synthetic test set)

How many orders skip human review at each auto threshold, and how often those are right.
Defaults were fixed before this evaluation; a shop can move its own slider.

| Auto threshold | Min margin | Auto-routed share | Auto accuracy |
|---|---|---|---|
${sweep.map((s) => `| ${s.auto} | ${s.margin} | ${pct(s.share)} | ${s.acc === null ? "n/a" : pct(s.acc)} |`).join("\n")}

### Feedback loop: a shop that phrases things differently

The seed model never saw this vocabulary. The shop corrects its first *k* orders; we then measure on 400 later orders.

| Corrections | Top-1 accuracy | Auto-routed | Auto accuracy | Review queue |
|---|---|---|---|---|
${curve.map((c) => `| ${c.corrections} | ${pct(c.top1)} | ${pct(c.autoRate)} | ${c.autoAcc === null ? "n/a" : pct(c.autoAcc)} | ${pct(c.reviewRate)} |`).join("\n")}
`;

mkdirSync("reports", { recursive: true });
writeFileSync("reports/eval.md", md);
writeFileSync("reports/eval.json", JSON.stringify({ test: { ...rTest, misses: undefined }, handwritten: { ...rHand }, curve, sweep }, null, 1));
console.log(md);
